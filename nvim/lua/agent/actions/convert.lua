-- Convert: a JSON sample, a SQL CREATE TABLE or a curl command (selected, or the paragraph under the cursor) becomes ready
-- code in the file's language, in its place. What it becomes is fixed per source and language (agent/convert.lua), so the
-- prompt is explicit and the answer predictable; a one-word instruction names the root type.
local convert = require "agent.convert"

--- The code generators of the Dart package a file belongs to (nil outside Dart)
---@param target AgentTarget
local function stack(target)
  if target.lang ~= "dart" then
    return nil
  end
  local root = vim.fs.root(target.buf, "pubspec.yaml")
  local f = root and io.open(root .. "/pubspec.yaml", "r")
  if not f then
    return nil
  end
  local text = f:read "*a"
  f:close()
  return convert.dart_stack(text)
end

--- The package renames every JSON field already (`field_rename` in build.yaml): no `@JsonKey` per field then
---@param target AgentTarget
---@return boolean
local function renames_fields(target)
  local root = vim.fs.root(target.buf, "pubspec.yaml")
  local f = root and io.open(root .. "/build.yaml", "r")
  if not f then
    return false
  end
  local text = f:read "*a"
  f:close()
  return text:find("field_rename", 1, true) ~= nil
end

return {
  label = "convert",
  desc = "convert",
  key = "t",
  scope = "lines",
  context = { "rules" },
  output = "replace",
  tier = "light",
  input = "root type name or what to make (empty: the usual)",
  input_optional = true,
  ---@param target AgentTarget
  check = function(target)
    if not convert.language(target.lang) then
      return "paste it in the code file where the result should go: " .. target.lang .. " is not a programming language"
    end
    if not convert.detect(target.lines) then
      return "select a JSON sample, a SQL CREATE TABLE or a curl command"
    end
  end,
  system = function(env)
    local kind = convert.detect(env.target.lines)
    local language = convert.language(env.target.lang)
    return (
      "TASK convert: <target> is %s. Replace it with %s.\n"
      .. "Name the root type with the instruction when it is a single word, else with a noun the data suggests (never Root, "
      .. "Data or AutoGenerated). The result must compile as it is in this file: no placeholders, no sample values, no main or "
      .. "usage example, no comments that repeat the field names. An instruction that asks for something else wins.\n"
      .. "OUTPUT: one fenced block with ONLY the code that replaces <target>; then, only if needed, one or both lines:\n"
      .. "needs-import: <imports>\n"
      .. "note: <max 15 words: what you assumed, e.g. a type guessed from a null value>\n"
      .. "The block is the final answer: no draft, no second block, no prose."
    ):format(convert.SOURCES[kind], convert.goal(kind, language, stack(env.target)))
  end,
  -- checked by rule, the same way every time (0 tokens): small models glue the declarations together, and in Dart they
  -- sometimes forget the `@JsonKey` of a snake_case key (that field would deserialize as null)
  merge = function(code, target)
    if target.lang == "dart" and convert.detect(target.lines) == "json" and not renames_fields(target) then
      local keys = convert.json_keys(target.lines)
      if keys then
        code = convert.dart_json_keys(code, keys)
      end
    end
    return convert.spaced(code, target.lang)
  end,
  task = function()
    return "Convert <target>."
  end,
}
